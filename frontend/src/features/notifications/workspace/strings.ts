export const WORDS = { ar: AR as Record<WordKey, string>, en: EN }

const PLURAL_AR: Record<string, string> = { مشروع: 'المشاريع', عميل: 'العملاء', علامة: 'العلامات', حملة: 'الحملات', حساب: 'الحسابات' }

export interface Terms { client: string; project: string }

export function pluralOf(term: string, ar: boolean): string {
  if (ar) return PLURAL_AR[term] ?? term
  return term.endsWith('s') ? term : `${term}s`
}

/** Fill `{name}` placeholders. Unknown placeholders are left as written (variables such as {project} in a template hint stay literal where intended). */
export function fill(text: string, vars: Record<string, string | number>): string {
  return text.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m))
}

/** `t('colProjects')` in the current language, with the workspace type's own terms filled in. */
export function useWords(terms?: Terms) {
  const ar = useUi((u) => u.locale) === 'ar'
  const dict = ar ? WORDS.ar : WORDS.en
  const client = terms?.client ?? (ar ? 'عميل' : 'Client')
  const project = terms?.project ?? (ar ? 'مشروع' : 'Project')
  const base = { client, project, projects: pluralOf(project, ar), clients: pluralOf(client, ar) }
  const t = (key: WordKey, vars: Record<string, string | number> = {}): string => fill(dict[key], { ...base, ...vars })

  return { t, ar, terms: base }
}
