use Tests\TestCase;

/**
 * LIFECYCLE-6 (Owner spec 2026-11-15 §6) — `alerts:reevaluate-data-arrival`: re-judges every open data-arrival alert by the
 * account-day rule and closes only the false ones; dry run by default, idempotent, reversible, counts only.
 *
 * Day D is covered for an account when a successful sync whose window includes D finished after the end of D in the
 * ACCOUNT's time zone plus the settle window (default 6 h). Zero spend is data. Archived/deleted projects are silent.
 * Fixtures only: every id here is generated by the test.
 */
final class DataArrivalReevaluateCommandTest extends TestCase
{
    use RefreshDatabase;

    /** 10:00 Riyadh, Sunday 15 November 2026: with a 6 h settle window and one cycle, the 14th must have arrived. */
    private const NOW_UTC = '2026-11-15 07:00:00';

    private Tenant $tenant;

    private ClientWorkspace $client;

    private Project $project;

    protected function setUp(): void
    {
        parent::setUp();
        Carbon::setTestNow(Carbon::parse(self::NOW_UTC, 'UTC'));
        config(['integrations.data_coverage.settle_hours' => 6, 'integrations.data_coverage.cycle_minutes' => 60]);
        $this->tenant = Tenant::create(['name' => 'T', 'slug' => 't-da-'.uniqid(), 'status' => 'active']);
        app(TenantContext::class)->setTenantId($this->tenant->id);
        $this->client = ClientWorkspace::create(['tenant_id' => $this->tenant->id, 'name' => 'Client', 'slug' => 'c-'.uniqid(), 'mode' => 'managed', 'status' => 'active']);
        $this->project = $this->project('Fixture Live Project');
    }

    protected function tearDown(): void
    {
        Carbon::setTestNow();
        parent::tearDown();
    }

    private function project(string $name, string $status = 'active'): Project
    {
        return Project::create(['tenant_id' => $this->tenant->id, 'client_workspace_id' => $this->client->id, 'name' => $name, 'status' => $status]);
    }

    /** @return array{0: ProviderConnection, 1: ExternalAccount} */
    private function account(string $provider, ?Project $project = null, ?string $timezone = 'Asia/Riyadh', string $name = 'Fixture Account', bool $active = true): array
    {
        $c = app(TokenVault::class)->open(
            tenantId: (string) $this->tenant->id, provider: $provider,
            tokens: new OAuthTokens('AT', 'RT', Carbon::now()->addHour()), connectionName: $provider.uniqid(),
        );
        $a = ExternalAccount::withoutGlobalScopes()->create([
            'tenant_id' => $this->tenant->id, 'provider_connection_id' => $c->getKey(), 'provider' => $provider, 'account_type' => 'ad_account',
            'external_id' => 'fx-'.substr(uniqid(), -6), 'name' => $name, 'currency' => 'SAR', 'timezone' => $timezone, 'status' => 'active',
        ]);
        ProjectIntegrationBinding::create([
            'tenant_id' => $this->tenant->id, 'project_id' => ($project ?? $this->project)->id, 'external_account_id' => $a->id,
            'provider' => $provider, 'purpose' => 'ads', 'is_active' => $active,
        ]);

        return [$c, $a];
    }

    private function syncRun(ExternalAccount $a, string $from, string $to, string $finishedUtc, string $status = 'success', ?Project $project = null): void
    {
        $at = Carbon::parse($finishedUtc, 'UTC');
        DB::table('metric_sync_runs')->insert([
            'id' => (string) Str::uuid(), 'tenant_id' => $this->tenant->id, 'project_id' => ($project ?? $this->project)->id,
            'connection_id' => $a->provider_connection_id, 'external_account_id' => $a->id, 'provider' => $a->provider, 'status' => $status,
            'window_start' => $from, 'window_end' => $to, 'metrics_upserted' => 0, 'error' => $status === 'failed' ? 'timeout' : null,
            'started_at' => $at->copy()->subMinute(), 'finished_at' => $at, 'created_at' => $at, 'updated_at' => $at,
        ]);
    }

    /** @param  array<string,mixed>  $threshold */
    private function rule(string $type = 'sync_failure', ?string $projectId = null, array $threshold = []): AlertRule
    {
        return AlertRule::create([
            'tenant_id' => $this->tenant->id, 'project_id' => $projectId, 'type' => $type, 'name' => $type, 'cooldown_minutes' => 720,
            'channels' => ['in_app'], 'severity' => 'warning', 'active' => true, 'threshold' => $threshold,
        ]);
    }

    private function sweep(AlertRule ...$rules): void
    {
        foreach ($rules as $rule) {
            app(TenantContext::class)->setTenantId($this->tenant->id);
            app(AlertEvaluator::class)->evaluateRule($rule);
        }
    }

    /** @return Collection<int, AlertEvent> */
    private function open()
    {
        return AlertEvent::withoutGlobalScopes()->whereIn('type', ['sync_failure', 'sync_outage'])->whereIn('status', ['open', 'snoozed'])->get();
    }

    public function test_the_ops_command_closes_only_false_alerts_dry_run_by_default_idempotent_and_undoable(): void
    {
        [, $ok] = $this->account('snapchat');
        $this->syncRun($ok, '2026-11-12', '2026-11-15', '2026-11-15 06:30:00');
        [, $bad] = $this->account('google', name: 'Secret Account Name');
        $this->syncRun($bad, '2026-11-08', '2026-11-11', '2026-11-11 06:00:00');
        $archived = $this->project('Secret Archived Name', 'archived');
        $rule = $this->rule();
        $mk = fn (string $entityType, string $entityId, ?string $projectId, array $ctx = []) => AlertEvent::create([
            'tenant_id' => $this->tenant->id, 'project_id' => $projectId, 'rule_id' => $rule->id, 'type' => 'sync_failure', 'entity_type' => $entityType,
            'entity_id' => $entityId, 'dedup_key' => Str::random(20), 'severity' => 'critical', 'status' => 'open',
            'context' => ['provider' => 'x', 'link_state' => 'not_synced'] + $ctx, 'last_triggered_at' => now()]);
        $falseCovered = $mk(ProviderConnection::class, (string) $ok->provider_connection_id, (string) $this->project->id);
        $falseArchived = $mk(Project::class, (string) $archived->id, (string) $archived->id, ['sources' => [['provider' => 'google']]]);
        $true = $mk(ProviderConnection::class, (string) $bad->provider_connection_id, (string) $this->project->id);
        app(TenantContext::class)->forget();

        $this->assertSame(0, Artisan::call('alerts:reevaluate-data-arrival'));
        $dry = Artisan::output();
        $this->assertStringContainsString('DRY RUN', $dry);
        $this->assertSame(3, AlertEvent::withoutGlobalScopes()->where('status', 'open')->count(), 'dry run writes nothing');

        $this->assertSame(0, Artisan::call('alerts:reevaluate-data-arrival', ['--apply' => true]));
        $out = Artisan::output();
        $this->assertSame('resolved', $falseCovered->refresh()->status);
        $this->assertSame('day_covered', $falseCovered->context['closed_reason']);
        $this->assertSame('resolved', $falseArchived->refresh()->status);
        $this->assertSame('project_not_live', $falseArchived->context['closed_reason']);
        $this->assertSame('open', $true->refresh()->status, 'a true alert stays open');
        // Counts only: no ids, no names.
        foreach ([$dry, $out] as $text) {
            foreach ([(string) $this->tenant->id, (string) $archived->id, (string) $falseCovered->id, 'Secret', $bad->external_id] as $secret) {
                $this->assertStringNotContainsString($secret, $text);
            }
        }

        // Idempotent.
        Artisan::call('alerts:reevaluate-data-arrival', ['--apply' => true]);
        $this->assertStringContainsString('closed: 0', Artisan::output());

        // Reversible.
        Artisan::call('alerts:reevaluate-data-arrival', ['--undo' => true, '--apply' => true]);
        $this->assertSame('open', $falseCovered->refresh()->status);
        $this->assertSame('open', $falseArchived->refresh()->status);
        $this->assertArrayNotHasKey('closed_reason', (array) $falseCovered->context);
    }
}
