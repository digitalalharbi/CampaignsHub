use Tests\TestCase;

/**
 * LIFECYCLE-6 (Owner spec 2026-11-15 §6) — «بيانات أمس ما وصلت من المنصة» only when it is true.
 *
 * Day D is covered for an account when a successful sync whose window includes D finished after the end of D in the
 * ACCOUNT's time zone plus the settle window (default 6 h). Zero spend is data. Archived/deleted projects are silent.
 * Fixtures only: every id here is generated by the test.
 */
final class DataArrivalCoverageTest extends TestCase
{
    use RefreshDatabase;

    /** 10:00 Riyadh, Sunday 15 November 2026: with a 6 h settle window and one cycle, the 14th must have arrived. */
    private const NOW_UTC = '2026-11-15 07:00:00';

    private Tenant $tenant;

    private ClientWorkspace $client;

    private Project $project;

    protected function setUp(): void
    {
        parent::setUp();
        Carbon::setTestNow(Carbon::parse(self::NOW_UTC, 'UTC'));
        config(['integrations.data_coverage.settle_hours' => 6, 'integrations.data_coverage.cycle_minutes' => 60]);
        $this->tenant = Tenant::create(['name' => 'T', 'slug' => 't-da-'.uniqid(), 'status' => 'active']);
        app(TenantContext::class)->setTenantId($this->tenant->id);
        $this->client = ClientWorkspace::create(['tenant_id' => $this->tenant->id, 'name' => 'Client', 'slug' => 'c-'.uniqid(), 'mode' => 'managed', 'status' => 'active']);
        $this->project = $this->project('Fixture Live Project');
    }

    protected function tearDown(): void
    {
        Carbon::setTestNow();
        parent::tearDown();
    }

    private function project(string $name, string $status = 'active'): Project
    {
        return Project::create(['tenant_id' => $this->tenant->id, 'client_workspace_id' => $this->client->id, 'name' => $name, 'status' => $status]);
    }

    /** @return array{0: ProviderConnection, 1: ExternalAccount} */
    private function account(string $provider, ?Project $project = null, ?string $timezone = 'Asia/Riyadh', string $name = 'Fixture Account', bool $active = true): array
    {
        $c = app(TokenVault::class)->open(
            tenantId: (string) $this->tenant->id, provider: $provider,
            tokens: new OAuthTokens('AT', 'RT', Carbon::now()->addHour()), connectionName: $provider.uniqid(),
        );
        $a = ExternalAccount::withoutGlobalScopes()->create([
            'tenant_id' => $this->tenant->id, 'provider_connection_id' => $c->getKey(), 'provider' => $provider, 'account_type' => 'ad_account',
            'external_id' => 'fx-'.substr(uniqid(), -6), 'name' => $name, 'currency' => 'SAR', 'timezone' => $timezone, 'status' => 'active',
        ]);
        ProjectIntegrationBinding::create([
            'tenant_id' => $this->tenant->id, 'project_id' => ($project ?? $this->project)->id, 'external_account_id' => $a->id,
            'provider' => $provider, 'purpose' => 'ads', 'is_active' => $active,
        ]);

        return [$c, $a];
    }

    private function syncRun(ExternalAccount $a, string $from, string $to, string $finishedUtc, string $status = 'success', ?Project $project = null): void
    {
        $at = Carbon::parse($finishedUtc, 'UTC');
        DB::table('metric_sync_runs')->insert([
            'id' => (string) Str::uuid(), 'tenant_id' => $this->tenant->id, 'project_id' => ($project ?? $this->project)->id,
            'connection_id' => $a->provider_connection_id, 'external_account_id' => $a->id, 'provider' => $a->provider, 'status' => $status,
            'window_start' => $from, 'window_end' => $to, 'metrics_upserted' => 0, 'error' => $status === 'failed' ? 'timeout' : null,
            'started_at' => $at->copy()->subMinute(), 'finished_at' => $at, 'created_at' => $at, 'updated_at' => $at,
        ]);
    }

    /** @param  array<string,mixed>  $threshold */
    private function rule(string $type = 'sync_failure', ?string $projectId = null, array $threshold = []): AlertRule
    {
        return AlertRule::create([
            'tenant_id' => $this->tenant->id, 'project_id' => $projectId, 'type' => $type, 'name' => $type, 'cooldown_minutes' => 720,
            'channels' => ['in_app'], 'severity' => 'warning', 'active' => true, 'threshold' => $threshold,
        ]);
    }

    private function sweep(AlertRule ...$rules): void
    {
        foreach ($rules as $rule) {
            app(TenantContext::class)->setTenantId($this->tenant->id);
            app(AlertEvaluator::class)->evaluateRule($rule);
        }
    }

    /** @return Collection<int, AlertEvent> */
    private function open()
    {
        return AlertEvent::withoutGlobalScopes()->whereIn('type', ['sync_failure', 'sync_outage'])->whereIn('status', ['open', 'snoozed'])->get();
    }

    public function test_a_covering_sync_raises_nothing(): void
    {
        [, $snap] = $this->account('snapchat');
        [, $google] = $this->account('google');
        // The production symptom: syncs every 30 minutes over a 12→15 window.
        $this->syncRun($snap, '2026-11-12', '2026-11-15', '2026-11-15 06:30:00');
        $this->syncRun($google, '2026-11-12', '2026-11-15', '2026-11-15 06:45:00');

        $this->sweep($this->rule(), $this->rule('sync_outage', (string) $this->project->id));

        $this->assertCount(0, $this->open());
    }

    public function test_no_coverage_after_the_window_alerts_with_project_and_account_named(): void
    {
        [, $snap] = $this->account('snapchat', name: 'Snap Fixture Account');
        $this->syncRun($snap, '2026-11-09', '2026-11-12', '2026-11-12 06:00:00');   // settled up to the 11th, nothing since

        $this->sweep($this->rule());

        $event = $this->open()->sole();
        $ctx = (array) $event->context;
        $this->assertSame((string) $this->project->id, (string) $event->project_id);
        $this->assertSame('no_coverage', $ctx['verdict']);
        $this->assertSame('2026-11-14', $ctx['required_day']);
        $this->assertSame('2026-11-11', $ctx['last_day']);
        $this->assertSame('Fixture Live Project', $ctx['project_name']);
        $this->assertSame('Snap Fixture Account', $ctx['account_name']);
        $this->assertSame($snap->external_id, $ctx['account_external_id']);
        $this->assertEquals(['finished_at' => '2026-11-12T06:00:00+00:00', 'window_start' => '2026-11-09', 'window_end' => '2026-11-12'], $ctx['last_success']);
        $this->assertNotSame('', $ctx['reason_ar']);
        $this->assertSame('critical', $event->severity, 'three days missing escalates');

        // The mail/bell text names the project and the account (never the bare «المشروع»).
        $text = AlertEventText::compose(['rule_type' => 'sync_failure', 'severity' => 'critical', 'context' => $ctx, 'project_id' => (string) $this->project->id,
            'project_name' => '', 'entity_type' => '', 'entity_id' => '', 'event_id' => (string) $event->id, 'triggered_at' => ''], true);
        $this->assertStringContainsString('Fixture Live Project', $text['context']);
        $this->assertStringContainsString($snap->external_id, $text['numbers']);
        $this->assertStringContainsString('Snap Fixture Account', $text['numbers']);
    }

    public function test_a_later_successful_sync_closes_the_alert(): void
    {
        [, $snap] = $this->account('snapchat');
        $this->syncRun($snap, '2026-11-09', '2026-11-12', '2026-11-12 06:00:00');
        $rule = $this->rule();
        $this->sweep($rule);
        $event = $this->open()->sole();
        $notices = DB::table('app_notifications')->count();

        $this->syncRun($snap, '2026-11-12', '2026-11-15', '2026-11-15 06:50:00');
        $this->sweep($rule);

        $this->assertSame('resolved', $event->refresh()->status);
        $this->assertSame('day_covered', $event->context['closed_reason']);
        $this->assertSame($notices, DB::table('app_notifications')->count(), 'closed without a second notice');
    }

    public function test_a_zero_spend_day_is_covered(): void
    {
        [, $snap] = $this->account('snapchat');
        [, $google] = $this->account('google');
        // The platform answered and there was nothing to report: no metric rows at all.
        $this->syncRun($snap, '2026-11-12', '2026-11-15', '2026-11-15 06:30:00', 'no_data');
        $this->syncRun($google, '2026-11-12', '2026-11-15', '2026-11-15 06:30:00', 'success');
        $this->assertSame(0, DB::table('daily_metrics')->count());

        $this->sweep($this->rule());

        $this->assertCount(0, $this->open());
    }

    public function test_an_archived_or_deleted_project_raises_nothing_and_its_open_alert_closes(): void
    {
        // The production shape: the live project syncs, an archived project (its account since unlinked) stopped on the 11th.
        [, $live] = $this->account('snapchat');
        $this->syncRun($live, '2026-11-12', '2026-11-15', '2026-11-15 06:30:00');
        $archived = $this->project('Fixture Archived Project', 'archived');
        [, $old] = $this->account('snapchat', $archived, active: false);
        $this->syncRun($old, '2026-11-08', '2026-11-11', '2026-11-11 06:00:00', project: $archived);
        $trashed = $this->project('Fixture Trashed Project');
        [, $gone] = $this->account('google', $trashed);
        $this->syncRun($gone, '2026-11-07', '2026-11-10', '2026-11-10 06:00:00', project: $trashed);
        $trashed->delete();
        $stale = AlertEvent::create(['tenant_id' => $this->tenant->id, 'project_id' => $archived->id, 'rule_id' => $this->rule()->id, 'type' => 'sync_failure',
            'entity_type' => ProviderConnection::class, 'entity_id' => (string) $old->provider_connection_id, 'dedup_key' => Str::random(20),
            'severity' => 'critical', 'status' => 'open', 'context' => ['provider' => 'snapchat', 'link_state' => 'not_synced', 'last_day' => '2026-11-11'], 'last_triggered_at' => now()]);

        $this->sweep($this->rule(), $this->rule('sync_failure', (string) $archived->id), $this->rule('sync_outage', (string) $archived->id));

        $this->assertCount(0, $this->open());
        $this->assertSame('resolved', $stale->refresh()->status);
        $this->assertSame('project_not_live', $stale->context['closed_reason']);
    }

    public function test_the_day_ends_in_the_accounts_own_time_zone(): void
    {
        // 08:00 UTC on the 12th: Riyadh's 11th is long over, Los Angeles' 11th ended at 08:00 UTC today.
        Carbon::setTestNow(Carbon::parse('2026-11-12 08:00:00', 'UTC'));
        [, $la] = $this->account('google', timezone: 'America/Los_Angeles');
        // A run that read the 10th after it settled in LA, but finished before LA's 11th ended.
        $this->syncRun($la, '2026-11-08', '2026-11-11', '2026-11-11 20:00:00');
        $rule = $this->rule();

        // In LA the 11th has only just ended, so it is not due yet: the 10th is required, and it is covered — no alert.
        $this->sweep($rule);
        $this->assertCount(0, $this->open(), 'Riyadh\'s «yesterday» is not the account\'s');

        // 15:30 UTC: LA's 11th ended 7.5 h ago, so it is due — and that run finished before it ended: not covered.
        Carbon::setTestNow(Carbon::parse('2026-11-12 15:30:00', 'UTC'));
        $this->sweep($rule);
        $event = $this->open()->sole();
        $this->assertSame('2026-11-11', $event->context['required_day']);
        $this->assertSame('America/Los_Angeles', $event->context['timezone']);

        // A run that finished after LA's 11th ended + 6 h covers it.
        $this->syncRun($la, '2026-11-09', '2026-11-12', '2026-11-12 14:10:00');
        $this->sweep($rule);
        $this->assertSame('resolved', $event->refresh()->status);
    }

    public function test_the_settle_window_setting_is_honoured(): void
    {
        [, $a] = $this->account('snapchat');
        // 03:00 Riyadh on the 15th: three hours after the 14th ended.
        $this->syncRun($a, '2026-11-12', '2026-11-15', '2026-11-15 00:00:00');
        Carbon::setTestNow(Carbon::parse('2026-11-15 05:30:00', 'UTC'));   // 08:30 Riyadh

        config(['integrations.data_coverage.settle_hours' => 2]);
        $this->sweep($this->rule());
        $this->assertCount(0, $this->open(), '2 h settle: the run finished 3 h after the day ended — covered');

        config(['integrations.data_coverage.settle_hours' => 6]);
        $this->sweep($this->rule());
        $event = $this->open()->sole();
        $this->assertSame('2026-11-14', $event->context['required_day']);
        $this->assertSame(6, $event->context['settle_hours']);

        // A rule may carry its own settle window.
        $event->forceFill(['status' => 'resolved'])->save();
        $this->sweep($this->rule('sync_failure', null, ['settle_hours' => 2]));
        $this->assertCount(0, $this->open());
    }

    public function test_a_persistently_failing_last_sync_alerts_with_that_reason(): void
    {
        [, $a] = $this->account('snapchat');
        $this->syncRun($a, '2026-11-12', '2026-11-15', '2026-11-15 05:00:00');            // covered the 14th
        $this->syncRun($a, '2026-11-12', '2026-11-15', '2026-11-15 06:30:00', 'failed');  // and 2 h without a success since
        $this->sweep($this->rule());
        $this->assertSame('last_sync_failed', $this->open()->sole()->context['verdict']);
    }

    public function test_one_transient_failure_after_a_success_is_not_an_alert(): void
    {
        [, $a] = $this->account('snapchat');
        $this->syncRun($a, '2026-11-12', '2026-11-15', '2026-11-15 06:30:00');
        $this->syncRun($a, '2026-11-12', '2026-11-15', '2026-11-15 06:45:00', 'failed');
        $this->sweep($this->rule());
        $this->assertCount(0, $this->open());
    }
}
